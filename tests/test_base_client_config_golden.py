def _describe(value: Any) -> Any:
    """
    Render a result as JSON-compatible data that pins its type and every field's ``repr``.

    Args:
        value (Any):
            A config, a nested dataclass, or a plain value.

    Returns:
        Any:
            ``{"type": ..., "fields": {...}}`` for a dataclass, ``value`` otherwise.
    """
    if is_dataclass(value) and not isinstance(value, type):
        return {
            "type": type(value).__name__,
            "fields": {config_field.name: repr(getattr(value, config_field.name)) for config_field in fields(value)},
        }
    return value


def _outcome(produce: Callable[[], Any]) -> Dict[str, Any]:
    """
    Run one case and record its result (or exception type) and any warnings it emitted.

    Args:
        produce (Callable[[], Any]):
            The case.

    Returns:
        Dict[str, Any]:
            ``{"result": ...}`` or ``{"error": <exception class name>}``, plus ``"warnings"``.
    """
    outcome: Dict[str, Any] = {}
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        try:
            outcome["result"] = _describe(produce())
        except Exception as error:
            outcome["error"] = type(error).__name__
    outcome["warnings"] = [f"{w.category.__name__}: {w.message}" for w in caught]
    return outcome


