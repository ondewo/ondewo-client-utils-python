def all_cases() -> Dict[str, Callable[[], Any]]:
    """
    Return every golden case.

    Returns:
        Dict[str, Callable[[], Any]]:
            Case id -> case.
    """
    return {**_encode_cases(), **_DECODE_CASES}


# Outcomes that changed on purpose when dataclasses-json was replaced. Each one is asserted
# explicitly, with its new value, in the region at the end of this module.
DELIBERATE_DIFFERENCES: FrozenSet[str] = frozenset(
    # to_json() without arguments is orjson's compact UTF-8 rendering of the same document.
    {f"{name}.to_json" for name in _BASE}
    | {
        # A missing mandatory field: TypeError (the constructor's own error) instead of KeyError.
        "from_dict.missing_mandatory_key",
        "from_dict.nested_missing_mandatory",
        # A document that is not an object: TypeError naming the class instead of AttributeError.
        "from_dict.none",
        "from_json.list_document",
        "from_json.string_document",
        "from_json.null_document",
        # bytes passed to from_dict for grpc_cert are kept, not turned into the text "b'PEM'".
        "from_dict.bytes_cert",
        # orjson rejects the non-standard NaN literal instead of feeding it to int().
        "from_json.nan_into_optional_int",
    }
)


def _golden() -> Dict[str, Any]:
    """
    Load the recorded outcomes.

    Returns:
        Dict[str, Any]:
            Case id -> outcome.
    """
    golden: Dict[str, Any] = json.loads(GOLDEN_PATH.read_text(encoding="utf-8"))
    return golden


def test_the_fixture_covers_exactly_the_cases() -> None:
    """Verify every case has a recorded outcome and no outcome is orphaned."""
    assert set(_golden()) == set(all_cases())


#: Fields added after the fixture was recorded. Unset, they are the only difference to the dataclasses-json era,
#: so the comparison drops them; their own behaviour is pinned in test_base_client_config.py.
FIELDS_ADDED_SINCE_THE_FIXTURE: FrozenSet[str] = frozenset({"grpc_client_cert", "grpc_client_key"})
_UNSET_ADDED_FIELD_IN_JSON: "re.Pattern[str]" = re.compile(
    r',\s*"(?:' + "|".join(sorted(FIELDS_ADDED_SINCE_THE_FIXTURE)) + r')":\s*null'
)


def _without_unset_added_fields(value: Any) -> Any:
    """
    Remove the fields added since the fixture, wherever an outcome renders them unset.

    Args:
        value (Any):
            An outcome or a part of one: a dict, a list, a JSON document or a plain value.

    Returns:
        Any:
            The same value without ``grpc_client_cert`` / ``grpc_client_key`` entries that are ``None``,
            the repr ``"None"`` or JSON ``null``.
    """
    if isinstance(value, dict):
        return {
            key: _without_unset_added_fields(item)
            for key, item in value.items()
            if not (key in FIELDS_ADDED_SINCE_THE_FIXTURE and item in (None, "None"))
        }
    if isinstance(value, list):
        return [_without_unset_added_fields(item) for item in value]
    if isinstance(value, str):
        return _UNSET_ADDED_FIELD_IN_JSON.sub("", value)
    return value


@pytest.mark.parametrize("case_id", sorted(set(all_cases()) - DELIBERATE_DIFFERENCES))
def test_the_outcome_matches_dataclasses_json(case_id: str) -> None:
    """Verify the case reproduces what dataclasses-json produced, byte for byte, apart from unset new fields."""
    assert _without_unset_added_fields(_outcome(all_cases()[case_id])) == _golden()[case_id]


# region the outcomes that differ from dataclasses-json ON PURPOSE (DELIBERATE_DIFFERENCES)


@pytest.mark.parametrize("name", sorted(_BASE))
def test_to_json_is_the_same_document_rendered_compact_and_utf8(name: str) -> None:
    """Verify ``to_json()`` is exactly dataclasses-json's document with orjson's compact UTF-8 layout."""
    old: str = _golden()[f"{name}.to_json"]["result"]
    new: str = _without_unset_added_fields(all_cases()[f"{name}.to_json"]())
    assert new == json.dumps(json.loads(old), separators=(",", ":"), ensure_ascii=False)
    assert json.loads(new) == json.loads(old)
    assert list(json.loads(new)) == list(json.loads(old))  # same key order


@pytest.mark.parametrize("case_id", ["from_dict.missing_mandatory_key", "from_dict.nested_missing_mandatory"])
def test_a_missing_mandatory_field_raises_type_error_instead_of_key_error(case_id: str) -> None:
    """Verify an absent field without a default raises the constructor's ``TypeError`` (was ``KeyError``)."""
    assert _golden()[case_id]["error"] == "KeyError"
    with pytest.raises(TypeError, match="missing 1 required"):
        all_cases()[case_id]()


@pytest.mark.parametrize(
    "case_id, received",
    [
        ("from_dict.none", "NoneType"),
        ("from_json.list_document", "list"),
        ("from_json.string_document", "str"),
        ("from_json.null_document", "NoneType"),
    ],
)
def test_a_document_that_is_not_an_object_raises_type_error(case_id: str, received: str) -> None:
    """Verify a non-object document raises a ``TypeError`` naming the class (was ``AttributeError``)."""
    assert _golden()[case_id]["error"] == "AttributeError"
    with pytest.raises(TypeError, match=f"BaseClientConfig must be decoded from a JSON object .*not {received}$"):
        all_cases()[case_id]()


def test_bytes_given_for_the_certificate_are_kept() -> None:
    """Verify ``from_dict`` keeps ``bytes`` as the constructor does (dataclasses-json made them ``"b'PEM'"``)."""
    assert _golden()["from_dict.bytes_cert"]["result"]["fields"]["grpc_cert"] == repr(b"b'PEM'")
    restored: BaseClientConfig = BaseClientConfig.from_dict({"host": "h", "port": "1", "grpc_cert": b"PEM"})
    assert restored == BaseClientConfig(host="h", port="1", grpc_cert="PEM")


def test_nan_is_rejected_as_invalid_json() -> None:
    """Verify orjson rejects the non-standard ``NaN`` literal (dataclasses-json fed it to ``int()``)."""
    assert _golden()["from_json.nan_into_optional_int"]["error"] == "ValueError"
    with pytest.raises(json.JSONDecodeError):
        all_cases()["from_json.nan_into_optional_int"]()


